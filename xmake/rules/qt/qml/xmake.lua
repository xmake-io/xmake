-- It packs the module resources and compiles them with the qt.qrc rule.
rule("qt.qml.resource")
    -- qt.qrc provides the rcc tool for the generated resource qrc
    add_deps("qt.qrc")

    -- Generate the resource qrc synchronously while the prepare job graph is being built,
    -- so the qmlcachegen/qmltc jobs of qt.qml (which read it with `--resource`) always
    -- see the final file. A normal prepare job runs concurrently with these jobs.
    on_prepare_files("prepare_resource", {jobgraph = true})

-- It packs the QML module resources and compiles them with qmlcachegen/qmltc.
--
-- The rule can be used directly by users together with the qt.quickapp rule (which
-- provides the Qt includes/links), e.g.:
--
-- target("app")
--     add_rules("qt.quickapp", "qt.qml")
--     add_files("*.qml", "*.js", "*.mjs")
--     add_values("qt.qml.uri", "MyApp")
--
rule("qt.qml")
    -- qt.env provides the Qt SDK, qt.qrc provides the rcc tool for the generated
    -- qrc, qt.moc provides the moc tool for the sources generated by qmltc
    add_deps("qt.env", "qt.qrc", "qt.moc")
    set_extensions(".qml", ".js", ".mjs", ".qmldir")

    on_load("load")

    on_config(function (target)
        import("utils")
        -- a target which only packs resources does not need qmlcachegen/qmltc
        local sourcebatch = target:sourcebatches()["qt.qml"]
        if sourcebatch and #sourcebatch.sourcefiles > 0 then
            local setting = utils.get_setting(target)
            local needs = utils.get_needs(setting, sourcebatch.sourcefiles)
            local aot = utils.get_aot(target, setting, utils.get_tools(target, setting, needs), needs)
            if aot.ignored then
                wprint("qt.qml: qt.qml.aot_stats is ignored because the AOT compilation is disabled")
            end
        end
    end)

    on_prepare_files("prepare_qml", {jobgraph = true})
